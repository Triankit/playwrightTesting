const nodemailer = require("nodemailer");
const fs = require("fs");
const { XMLParser } = require("fast-xml-parser");

const RESULT_FILE = "test-results/results.xml";

/**
 * Convert a value to an array.
 */
function toArray(value) {
	if (!value) {
		return [];
	}

	return Array.isArray(value) ? value : [value];
}

/**
 * Escape HTML characters so test names cannot break the email HTML.
 */
function escapeHtml(value) {
	return String(value ?? "")
		.replace(/&/g, "&amp;")
		.replace(/</g, "&lt;")
		.replace(/>/g, "&gt;")
		.replace(/"/g, "&quot;")
		.replace(/'/g, "&#039;");
}

/**
 * Read JUnit XML generated by Playwright.
 */
function parseTestResults() {
	if (!fs.existsSync(RESULT_FILE)) {
		throw new Error(`JUnit result file not found: ${RESULT_FILE}`);
	}

	const xml = fs.readFileSync(RESULT_FILE, "utf8");

	const parser = new XMLParser({
		ignoreAttributes: false,
		attributeNamePrefix: "@_",
	});

	const result = parser.parse(xml);

	let suites = [];

	/*
	 * Playwright JUnit output normally looks like:
	 *
	 * <testsuites>
	 *   <testsuite>
	 *     <testcase />
	 *   </testsuite>
	 * </testsuites>
	 */

	if (result.testsuites?.testsuite) {
		suites = toArray(result.testsuites.testsuite);
	} else if (result.testsuite) {
		suites = toArray(result.testsuite);
	}

	const tests = [];

	for (const suite of suites) {
		const suiteName =
			suite["@_name"] || suite["@_classname"] || "Unknown Suite";

		const testCases = toArray(suite.testcase);

		for (const testCase of testCases) {
			const testName = testCase["@_name"] || "Unknown Test";

			/*
			 * JUnit:
			 *
			 * failure -> failed
			 * error   -> failed
			 * skipped -> skipped
			 * nothing -> passed
			 */

			let status = "PASS";

			if (testCase.failure || testCase.error) {
				status = "FAIL";
			} else if (testCase.skipped) {
				status = "SKIPPED";
			}

			tests.push({
				suite: suiteName,
				testName,
				status,
			});
		}
	}

	return tests;
}

/**
 * Group tests by suite.
 */
function groupTestsBySuite(tests) {
	const groups = {};

	for (const test of tests) {
		if (!groups[test.suite]) {
			groups[test.suite] = [];
		}

		groups[test.suite].push(test);
	}

	return groups;
}

/**
 * Get suite statistics.
 */
function getSuiteStats(tests) {
	const passed = tests.filter((test) => test.status === "PASS").length;

	const failed = tests.filter((test) => test.status === "FAIL").length;

	const skipped = tests.filter((test) => test.status === "SKIPPED").length;

	return {
		total: tests.length,
		passed,
		failed,
		skipped,
	};
}

/**
 * Create overall statistics.
 */
function getOverallStats(tests) {
	return getSuiteStats(tests);
}

/**
 * Create a visual summary chart using HTML.
 *
 * Example:
 *
 * ███████████████████████░░░░░░
 * Passed        Failed       Skipped
 */
function createSummaryChart(stats) {
	const total = stats.total;

	if (total === 0) {
		return `
      <div style="
        padding:15px;
        background:#f8f8f8;
        border-radius:6px;
        margin:20px 0;
      ">
        No test results found.
      </div>
    `;
	}

	const passedWidth = (stats.passed / total) * 100;

	const failedWidth = (stats.failed / total) * 100;

	const skippedWidth = (stats.skipped / total) * 100;

	return `
    <div style="
      margin:25px 0;
      font-family:Arial,sans-serif;
    ">

      <h2 style="
        margin-bottom:15px;
        color:#333;
      ">
        Test Execution Summary
      </h2>

      <!-- Chart -->

      <table
        width="100%"
        cellpadding="0"
        cellspacing="0"
        style="
          border-collapse:collapse;
          height:35px;
          border-radius:6px;
          overflow:hidden;
        "
      >

        <tr>

          ${
						stats.passed > 0
							? `
                <td
                  width="${passedWidth}%"
                  style="
                    background:#2e7d32;
                    height:35px;
                  "
                ></td>
              `
							: ""
					}

          ${
						stats.failed > 0
							? `
                <td
                  width="${failedWidth}%"
                  style="
                    background:#d32f2f;
                    height:35px;
                  "
                ></td>
              `
							: ""
					}

          ${
						stats.skipped > 0
							? `
                <td
                  width="${skippedWidth}%"
                  style="
                    background:#f9a825;
                    height:35px;
                  "
                ></td>
              `
							: ""
					}

        </tr>

      </table>

      <!-- Legend -->

      <table
        width="100%"
        cellpadding="5"
        cellspacing="0"
        style="
          margin-top:12px;
          border-collapse:collapse;
        "
      >

        <tr>

          <td>
            🟢
            <strong>Passed:</strong>
            ${stats.passed}
          </td>

          <td>
            🔴
            <strong>Failed:</strong>
            ${stats.failed}
          </td>

          <td>
            🟡
            <strong>Skipped:</strong>
            ${stats.skipped}
          </td>

          <td>
            <strong>Total:</strong>
            ${stats.total}
          </td>

        </tr>

      </table>

    </div>
  `;
}

/**
 * Create one suite section.
 *
 * Example:
 *
 * 📁 Login Suite
 * 2 Passed | 1 Failed
 *
 * ✅ Valid Login
 * ❌ Invalid Password
 */
function createSuiteSection(suiteName, tests) {
	const stats = getSuiteStats(tests);

	let testRows = "";

	for (const test of tests) {
		let icon;
		let statusText;
		let statusColor;

		if (test.status === "PASS") {
			icon = "✅";
			statusText = "PASS";
			statusColor = "#2e7d32";
		} else if (test.status === "FAIL") {
			icon = "❌";
			statusText = "FAIL";
			statusColor = "#d32f2f";
		} else {
			icon = "🟡";
			statusText = "SKIPPED";
			statusColor = "#f9a825";
		}

		testRows += `
      <tr>

        <td style="
          padding:10px;
          border-bottom:1px solid #eeeeee;
          width:70%;
        ">

          ${icon}

          <span style="
            margin-left:8px;
            color:#333;
          ">
            ${escapeHtml(test.testName)}
          </span>

        </td>

        <td style="
          padding:10px;
          border-bottom:1px solid #eeeeee;
          color:${statusColor};
          font-weight:bold;
          text-align:right;
        ">

          ${statusText}

        </td>

      </tr>
    `;
	}

	return `
    <div style="
      margin:20px 0;
      border:1px solid #dddddd;
      border-radius:8px;
      overflow:hidden;
      font-family:Arial,sans-serif;
    ">

      <!-- Suite Header -->

      <div style="
        background:#f5f5f5;
        padding:14px 16px;
      ">

        <table
          width="100%"
          cellpadding="0"
          cellspacing="0"
          style="border-collapse:collapse;"
        >

          <tr>

            <td>

              <strong style="
                font-size:16px;
                color:#333;
              ">

                📁
                ${escapeHtml(suiteName)}

              </strong>

            </td>

            <td style="
              text-align:right;
              font-size:13px;
            ">

              <span style="
                color:#2e7d32;
                font-weight:bold;
              ">
                ${stats.passed} Passed
              </span>

              &nbsp; | &nbsp;

              <span style="
                color:#d32f2f;
                font-weight:bold;
              ">
                ${stats.failed} Failed
              </span>

              ${
								stats.skipped > 0
									? `
                    &nbsp; | &nbsp;

                    <span style="
                      color:#f9a825;
                      font-weight:bold;
                    ">
                      ${stats.skipped} Skipped
                    </span>
                  `
									: ""
							}

            </td>

          </tr>

        </table>

      </div>

      <!-- Test Names -->

      <table
        width="100%"
        cellpadding="0"
        cellspacing="0"
        style="
          border-collapse:collapse;
        "
      >

        ${testRows}

      </table>

    </div>
  `;
}

/**
 * Create all suite sections.
 */
function createAllSuiteSections(tests) {
	const groupedSuites = groupTestsBySuite(tests);

	let html = "";

	for (const [suiteName, suiteTests] of Object.entries(groupedSuites)) {
		html += createSuiteSection(suiteName, suiteTests);
	}

	return html;
}

